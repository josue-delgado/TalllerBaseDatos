CREATE TABLE producto (
    producto_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_producto VARCHAR2(100) NOT NULL,
    precio_unitario NUMBER(10, 2) NOT NULL
);

CREATE TABLE lote (
    lote_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id        NUMBER NOT NULL,
    cantidad_producto  NUMBER NOT NULL,
    fecha_ingreso      DATE DEFAULT SYSDATE NOT NULL,
    fecha_vencimiento  DATE NOT NULL,
    CONSTRAINT fk_lote_producto FOREIGN KEY (producto_id) REFERENCES producto(producto_id)
);

CREATE TABLE cliente (
    cliente_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rut        VARCHAR2(12) NOT NULL UNIQUE,
    nombre     VARCHAR2(100) NOT NULL,
    email      VARCHAR2(100)
);

CREATE TABLE pedido (
    pedido_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id   NUMBER NOT NULL,
    fecha_pedido DATE DEFAULT SYSDATE NOT NULL,
    estado       VARCHAR2(30) NOT NULL,
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (cliente_id) REFERENCES cliente(cliente_id)
);

CREATE TABLE detalle (
    detalle_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id  NUMBER NOT NULL,
    lote_id    NUMBER NOT NULL,
    cantidad   NUMBER NOT NULL,
    subtotal   NUMBER(12, 2) NOT NULL,
    CONSTRAINT fk_detalle_pedido FOREIGN KEY (pedido_id) REFERENCES pedido(pedido_id),
    CONSTRAINT fk_detalle_lote FOREIGN KEY (lote_id) REFERENCES lote(lote_id)
);